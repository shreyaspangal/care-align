/**
 * Generates .env.test.local from a running local Supabase instance, for the
 * RLS proof tests (__tests__/rls/*). Gitignored, dev-only — CI sets the same
 * three vars directly in the environment instead of writing this file.
 *
 * Deliberately a separate file from .env.local: .env.local holds this
 * project's real production Supabase credentials (needed for `pnpm dev`
 * against seeded data, `pnpm eval`, etc.), and the RLS proof tests create
 * and delete real users/families/storage objects — they must never be able
 * to fall through to production credentials just because this file is
 * missing (see lib/test/supabase-test-env.ts, which refuses to run against
 * anything that isn't a local URL).
 *
 * Run: npx supabase start   (once, if not already running)
 *      node scripts/write-test-env.mjs
 */
import { execSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'

const raw = execSync('npx supabase status -o env', { encoding: 'utf8' })

function extract(varName) {
  const match = raw.match(new RegExp(`^${varName}="(.*)"$`, 'm'))
  if (!match) {
    throw new Error(
      `Could not find ${varName} in \`supabase status -o env\` output — is the local stack running? (npx supabase start)`
    )
  }
  return match[1]
}

const url = extract('API_URL')
const publishableKey = extract('PUBLISHABLE_KEY')
const serviceRoleKey = extract('SERVICE_ROLE_KEY')

writeFileSync(
  '.env.test.local',
  `# Generated by scripts/write-test-env.mjs — do not edit by hand, do not commit.
# Local Supabase only. Re-run this script after \`supabase db reset\` or a
# fresh \`supabase start\` (the local project's keys are stable across
# restarts, but this file can drift if you edit .env.test.local directly).
NEXT_PUBLIC_SUPABASE_URL=${url}
NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${publishableKey}
SUPABASE_SERVICE_ROLE_KEY=${serviceRoleKey}
`
)

console.log('Wrote .env.test.local from the local Supabase instance.')
